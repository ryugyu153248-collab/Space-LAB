import type { AttitudeMode, BurnDirection } from '@/types';

export type EventType = 'burn' | 'eclipse' | 'collision' | 'deployment' | 'docking' | 'attitude' | 'access' | 'reentry' | 'communication';

export type EventStatus = 'scheduled' | 'active' | 'completed' | 'failed' | 'disabled';

export interface VisualEffectSpec {
  /** how the effect should look; interpreted by the renderer */
  kind: 'none' | 'thruster-plume' | 'burn-vector' | 'impact-flash' | 'debris-cloud' | 'label';
  color?: string;
}

/** User-created, schedulable event. Computed events (eclipse/access/communication) are generated by analysis and are not stored. */
export interface SimEvent {
  id: string;
  name: string;
  type: EventType;
  /** UTC epoch-ms */
  start: number;
  end?: number;
  /** involved object ids (satellites / ground stations) */
  objects: string[];
  params: Record<string, number | string | boolean | undefined>;
  enabled: boolean;
  priority: number;
  dependsOn: string[];
  visual: VisualEffectSpec;
  /** key of the simulation handler in the registry */
  handlerId: EventType;
}

export const EVENT_COLORS: Record<EventType, string> = {
  burn: '#f97316', eclipse: '#a78bfa', collision: '#ef4444', deployment: '#22d3ee', docking: '#34d399',
  attitude: '#facc15', access: '#4ade80', reentry: '#fb7185', communication: '#60a5fa',
};

export type BurnParams = { kind: 'impulsive' | 'finite'; direction: BurnDirection; dv?: number; thrust?: number; duration?: number; isp: number };
export type AttitudeParams = { mode: AttitudeMode; slewSec: number; lat?: number; lon?: number; alt?: number };
