import { useStore } from '@/stores/store';
import { clock } from '@/engine/simulation/runtime';
import { downloadText, safeName, toCsv } from '@/engine/exporters/files';
import { accessReportHtml, conjunctionReportHtml, maneuverReportHtml, maneuverRows, missionReportHtml, type ReportInput } from '@/engine/exporters/reports';
import { deriveScenario } from '@/engine/events/EventManager';
import { sampleEphemeris } from '@/engine/orbital/ephemeris';
import { propagateSatellite } from '@/engine/orbital/propagate';
import { DEG } from '@/engine/orbital/constants';
import { serializeScenario } from '@/engine/data/scenario';

export function useReportInput(): ReportInput {
  const s = useStore();
  const c = clock.snapshot();
  return { name: s.scenarioName, base: s.baseSatellites, events: s.events, stations: s.stations, t0: c.start, t1: c.end, primaryId: s.selectedId, secondaryId: s.secondId, cov: { use: s.settings.useCovariance, primary: s.settings.covPrimary, secondary: s.settings.covSecondary, hbr: s.settings.hbr } };
}

export const exportActions = (inp: ReportInput, snapshot: () => ReturnType<typeof serializeScenario extends (x: infer X) => string ? () => X : never>) => {
  const n = safeName(inp.name);
  const derived = () => deriveScenario(inp.base, inp.events, inp.t1, inp.t0).satellites;
  return {
    missionHtml: () => downloadText(missionReportHtml(inp), `${n}_mission_report.html`, 'text/html'),
    accessHtml: () => { const r = accessReportHtml(inp); downloadText(r.html, `${n}_access_report.html`, 'text/html'); },
    accessCsv: () => downloadText(accessReportHtml(inp).csv, `${n}_access.csv`, 'text/csv'),
    conjHtml: () => downloadText(conjunctionReportHtml(inp).html, `${n}_conjunction_report.html`, 'text/html'),
    conjCsv: () => downloadText(conjunctionReportHtml(inp).csv, `${n}_conjunctions.csv`, 'text/csv'),
    maneuverHtml: () => downloadText(maneuverReportHtml(inp), `${n}_maneuver_report.html`, 'text/html'),
    maneuverCsv: () => downloadText(toCsv(maneuverRows(derived())), `${n}_maneuvers.csv`, 'text/csv'),
    ephemerisCsv: (satId: string | null, stepSec = 60) => {
      const s = derived().find((x) => x.id === satId); if (!s) return;
      const rows: (string | number)[][] = [['utc', 'model', 'lat_deg', 'lon_deg', 'alt_km', 'x_m_eci', 'y_m_eci', 'z_m_eci', 'vx_mps', 'vy_mps', 'vz_mps', 'speed_mps']];
      for (let t = inp.t0; t <= inp.t1; t += stepSec * 1000) {
        const st = propagateSatellite(s, t); if (!st) continue;
        const p = sampleEphemeris(s, t, t, 1)[0];
        rows.push([new Date(t).toISOString(), st.model, p.geo.lat / DEG, p.geo.lon / DEG, p.geo.alt / 1000, ...st.r, ...st.v, p.speed]);
      }
      downloadText(toCsv(rows), `${n}_${safeName(s.name)}_ephemeris.csv`, 'text/csv');
    },
    analysisJson: () => downloadText(JSON.stringify({ name: inp.name, window: [inp.t0, inp.t1], satellites: derived().filter((s) => s.kind !== 'debris').map((s) => ({ id: s.id, name: s.name, origin: s.origin, epoch: s.epoch, maneuvers: s.maneuvers })), events: inp.events }, null, 2), `${n}_analysis.json`, 'application/json'),
    scenarioJson: () => downloadText(serializeScenario(snapshot() as never), `${n}.scenario.json`, 'application/json'),
  };
};

export function ReportPanel() {
  const inp = useReportInput();
  const snapshot = useStore((s) => s.snapshot);
  const a = exportActions(inp, snapshot as never);
  const selectedId = useStore((s) => s.selectedId);
  const Btn = ({ l, f }: { l: string; f: () => void }) => <button className="btn" onClick={f}>{l}</button>;
  return (
    <div className="p-3 text-[11px] space-y-3 overflow-y-auto h-full">
      <div className="text-slate-500 uppercase tracking-widest text-[10px]">Reports (self-contained HTML — print to PDF from the browser) and data</div>
      <div className="flex flex-wrap gap-2"><Btn l="Mission report (HTML)" f={a.missionHtml} /><Btn l="Access report (HTML)" f={a.accessHtml} /><Btn l="Access (CSV)" f={a.accessCsv} /><Btn l="Conjunction report (HTML)" f={a.conjHtml} /><Btn l="Conjunctions (CSV)" f={a.conjCsv} /><Btn l="Maneuver report (HTML)" f={a.maneuverHtml} /><Btn l="Maneuvers (CSV)" f={a.maneuverCsv} /></div>
      <div className="flex flex-wrap gap-2"><Btn l="Ephemeris of selected satellite (CSV, 60 s)" f={() => a.ephemerisCsv(selectedId)} /><Btn l="Analysis (JSON)" f={a.analysisJson} /><Btn l="Scenario (JSON)" f={a.scenarioJson} /></div>
      <div className="text-slate-500">Reports are generated by recomputing the analyses from the current scenario. Conjunction and Pc statements follow the covariance settings in the Conjunction tab.</div>
    </div>
  );
}
